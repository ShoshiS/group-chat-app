import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const outputPath = join(
  dirname(fileURLToPath(import.meta.url)),
  '../src/environments/environment.production.ts',
);

const LOCAL_API = 'http://localhost:3001/api';
const LOCAL_SOCKET = 'http://localhost:3001';

/** Ensure a value is a full https URL (Render fromService.host has no scheme). */
function toOrigin(value) {
  const trimmed = value.trim().replace(/\/$/, '');
  if (!trimmed) {
    return '';
  }
  if (trimmed.startsWith('http://') || trimmed.startsWith('https://')) {
    return trimmed;
  }
  return `https://${trimmed}`;
}

function resolveProductionUrls() {
  const apiUrlEnv = process.env.API_URL?.trim();
  const socketUrlEnv = process.env.SOCKET_URL?.trim();
  const apiHost = process.env.API_HOST?.trim();

  if (apiUrlEnv) {
    const apiUrl = apiUrlEnv.replace(/\/$/, '');
    const socketUrl = socketUrlEnv
      ? toOrigin(socketUrlEnv)
      : apiUrl.replace(/\/api$/, '') || LOCAL_SOCKET;
    return { apiUrl, socketUrl };
  }

  if (apiHost) {
    const origin = toOrigin(apiHost);
    return { apiUrl: `${origin}/api`, socketUrl: origin };
  }

  return { apiUrl: LOCAL_API, socketUrl: LOCAL_SOCKET };
}

function escapeString(value) {
  return value.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

const { apiUrl, socketUrl } = resolveProductionUrls();
const googleClientId = (process.env.GOOGLE_CLIENT_ID ?? '').trim();

const contents = `/** Generated by scripts/generate-environment.mjs — do not edit manually. */
export const environment = {
  production: true,
  apiUrl: '${escapeString(apiUrl)}',
  socketUrl: '${escapeString(socketUrl)}',
  googleClientId: '${escapeString(googleClientId)}',
};
`;

writeFileSync(outputPath, contents, 'utf8');
console.log(`Wrote ${outputPath}`);
console.log(`  apiUrl: ${apiUrl}`);
console.log(`  socketUrl: ${socketUrl}`);
